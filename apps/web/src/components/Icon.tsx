export interface IconProps {
  icon: IconDefinition;
  /** Font Awesome size: xs, sm, lg, xl, 2xl (default: 1x) */
  size?: 'xs' | 'sm' | 'lg' | 'xl' | '2xl';
  /** Fixed-width container so columns align (default: true) */
  fixedWidth?: boolean;
  className?: string;
}

export function Icon({ icon, size, fixedWidth = true, className }: IconProps): ReactElement {
  return <FontAwesomeIcon icon={icon} size={size} fixedWidth={fixedWidth} className={className} />;
}

